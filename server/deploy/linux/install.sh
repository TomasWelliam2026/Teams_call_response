#!/usr/bin/env bash
# Sets up the call bridge server on this Linux VPS, always on, behind HTTPS. Also updates an existing
# setup: run it again from a newer copy, or after the VPS's IP changed. Easiest: sudo bash setup.sh
#
# What it does:
#   1. Copies the server into /opt/call-bridge (--dir to change) and runs it as the system user
#      "callbridge". Gets what it needs, if missing: Node.js (a private copy in bin/node unless Node
#      20.6+ is installed), Caddy (bin/caddy) and the npm packages. Downloads are checksum-verified.
#   2. Creates .env with two new random tokens, unless it exists. To move a server to this VPS and keep
#      its tokens (so the extension and the app keep working), put the old .env next to setup.sh first.
#   3. Writes the Caddyfile: HTTPS with free Let's Encrypt certificates for this VPS's IP, as
#      <ip>.sslip.io, <ip>.nip.io and the bare IP, plus your own domain with --domain.
#   4. Opens TCP 80 and 443 and UDP 3478 plus 49152-49452 in ufw or firewalld, if one is active.
#   5. Installs three systemd services that start at boot and restart if they stop:
#        callbridge-server  node server.js on 127.0.0.1:<port> (not reachable from outside)
#        callbridge-https   Caddy, the HTTPS front for all the names above
#        callbridge-turn    node turn-server.js, the camera-control relay
#      and the "callbridge" command (status, logs, restart, ...).
#   6. Starts them and checks the server answers over HTTPS.
#
# Options:
#   --domain bridge.example.com  Also answer on your own domain (point its DNS A record here first).
#                                Remembered in .env; --domain none drops it.
#   --ip 1.2.3.4                 Use this public IP instead of the one detected.
#   --port 8080                  Local port of server.js.
#   --dir /opt/call-bridge       Where to install.
#   --yes                        Don't ask before restarting a server that has live calls.
#
# Undo with: sudo callbridge uninstall
set -euo pipefail

NODE_MAJOR=24          # LTS line downloaded when this machine has no usable Node
CADDY_MIN=2.10.0       # first Caddy that can get certificates for a bare IP (profile shortlived)
SERVICE_USER=callbridge
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

DIR=/opt/call-bridge DOMAIN_ARG='' IP='' PORT='' YES=0

say()  { printf '%s\n' "$*"; }
warn() { printf '\033[33m%s\033[0m\n' "$*"; }
die()  { printf '\033[31mError: %s\033[0m\n' "$*" >&2; exit 1; }

# version_ge 2.11.9 2.10.0
version_ge() { [ "$(printf '%s\n%s\n' "$2" "$1" | sort -V | head -n1)" = "$2" ]; }

is_public_ipv4() {
  local ip=$1 o
  [[ $ip =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]] || return 1
  for o in "${BASH_REMATCH[@]:1}"; do [ "$o" -le 255 ] || return 1; done
  [[ ! $ip =~ ^(0\.|127\.|10\.|192\.168\.|169\.254\.|172\.(1[6-9]|2[0-9]|3[01])\.|100\.(6[4-9]|[7-9][0-9]|1[01][0-9]|12[0-7])\.) ]]
}

# The address the internet reaches this VPS at. Asked from outside first, because on many clouds the
# public IP isn't on any network interface (NAT); falls back to the interface of the default route.
detect_ip() {
  local url ip
  for url in https://api.ipify.org https://ifconfig.me/ip https://icanhazip.com; do
    ip=$(curl -4 -fsS --max-time 6 "$url" 2>/dev/null | tr -d '[:space:]') || continue
    if is_public_ipv4 "$ip"; then printf '%s' "$ip"; return; fi
  done
  ip=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i < NF; i++) if ($i == "src") print $(i + 1)}')
  if is_public_ipv4 "$ip"; then printf '%s' "$ip"; fi
}

# Every name the server answers on: your own domain (if any), two free wildcard-DNS names, and the bare IP.
site_names() {
  local ip=$1 domain=$2 dashed=${1//./-}
  [ -n "$domain" ] && printf '%s\n' "$domain"
  printf '%s\n' "$dashed.sslip.io" "$dashed.nip.io" "$ip"
}

env_get() { [ -f "$ENV_FILE" ] && sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" "$ENV_FILE" | tail -n1 | tr -d '\r' || true; }

# Sets KEY=value in .env, keeping every other line (comments included) as it is.
env_set() {
  local key=$1 value=$2 tmp
  tmp=$(mktemp)
  awk -v k="$key" -v v="$value" '
    $0 ~ "^[[:space:]]*" k "[[:space:]]*=" { if (!done) print k "=" v; done = 1; next }
    { sub(/\r$/, ""); print }
    END { if (!done) print k "=" v }' "$ENV_FILE" > "$tmp"
  cat "$tmp" > "$ENV_FILE"
  rm -f "$tmp"
}

new_token() { head -c 24 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'; }

write_caddyfile() {
  local ip=$1 domain=$2 port=$3 names
  names=$(site_names "$ip" "$domain" | grep -vxF "$ip" | paste -sd, - | sed 's/,/, /g')
  cat > "$CADDYFILE" <<EOF
# Generated by setup (deploy/linux/install.sh). Re-run setup instead of editing: it rewrites this file.
# Several names (and the bare IP) for the same server, so a network that blocks one can use another.
{
	admin off
}

$names {
	reverse_proxy 127.0.0.1:$port
}

# Let's Encrypt only issues certificates for IP addresses with its short-lived (6-day) profile;
# Caddy renews them automatically.
$ip {
	tls {
		issuer acme {
			profile shortlived
		}
	}
	reverse_proxy 127.0.0.1:$port
}
EOF
}

node_ok() { [ -x "$1" ] && "$1" -e 'const [a, b] = process.versions.node.split(".").map(Number); process.exit(a > 20 || (a === 20 && b >= 6) ? 0 : 1)' 2>/dev/null; }

# Node 20.6+ (for --env-file): the one on PATH if it is new enough, else a private copy in bin/node.
get_node() {
  local local_node="$DIR/bin/node/bin/node" system_node arch base line hash name tmp
  # A distro's node package may come without npm; only use it with npm next to it.
  system_node=$(command -v node || true)
  [ -n "$system_node" ] && [ -x "$(dirname "$system_node")/npm" ] || system_node=''
  local n
  for n in "$local_node" "$system_node"; do
    if [ -n "$n" ] && node_ok "$n"; then NODE=$n; return; fi
  done
  case "$(uname -m)" in
    x86_64) arch=x64 ;; aarch64|arm64) arch=arm64 ;; *) die "No Node.js build for $(uname -m). Install Node 20.6+ yourself and run setup again." ;;
  esac
  base="https://nodejs.org/dist/latest-v$NODE_MAJOR.x"
  say "Downloading Node.js $NODE_MAJOR ($arch) from nodejs.org..."
  line=$(curl -fsSL "$base/SHASUMS256.txt" | grep -E "  node-v[0-9.]+-linux-$arch\.tar\.gz$")
  hash=${line%% *} name=${line##* }
  tmp=$(mktemp -d)
  curl -fsSL -o "$tmp/$name" "$base/$name"
  (cd "$tmp" && printf '%s  %s\n' "$hash" "$name" | sha256sum -c --quiet -) || die "Checksum mismatch for $name. Run setup again."
  rm -rf "$DIR/bin/node" && mkdir -p "$DIR/bin/node"
  tar -xzf "$tmp/$name" -C "$DIR/bin/node" --strip-components=1
  rm -rf "$tmp"
  NODE=$local_node
  say "Installed Node $("$NODE" --version) in $DIR/bin/node."
}

# bin/caddy, downloaded (and checksum-verified) from Caddy's GitHub releases if missing or too old.
get_caddy() {
  local caddy="$DIR/bin/caddy" v arch tag ver name tmp
  if [ -x "$caddy" ]; then
    v=$("$caddy" version | sed -E 's/^v([0-9.]+).*/\1/')
    if version_ge "$v" "$CADDY_MIN"; then CADDY=$caddy; return; fi
    say "Caddy $v is too old (needs $CADDY_MIN+); updating."
  fi
  case "$(uname -m)" in
    x86_64) arch=amd64 ;; aarch64|arm64) arch=arm64 ;; armv7l) arch=armv7 ;; *) die "No Caddy build for $(uname -m)." ;;
  esac
  # The "latest" page redirects to .../tag/vX.Y.Z; no GitHub API (and its rate limit) needed.
  tag=$(curl -fsSLI -o /dev/null -w '%{url_effective}' https://github.com/caddyserver/caddy/releases/latest)
  ver=${tag##*/v}
  [[ $ver =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "Couldn't find Caddy's latest version. Put a caddy binary in $DIR/bin by hand."
  name="caddy_${ver}_linux_$arch.tar.gz"
  say "Downloading Caddy $ver ($arch) from GitHub..."
  tmp=$(mktemp -d)
  curl -fsSL -o "$tmp/$name" "https://github.com/caddyserver/caddy/releases/download/v$ver/$name"
  curl -fsSL -o "$tmp/sums" "https://github.com/caddyserver/caddy/releases/download/v$ver/caddy_${ver}_checksums.txt"
  (cd "$tmp" && grep -E "  $name\$" sums | sha512sum -c --quiet -) || die "Checksum mismatch for $name. Run setup again."
  tar -xzf "$tmp/$name" -C "$tmp" caddy
  install -m 755 "$tmp/caddy" "$caddy"
  rm -rf "$tmp"
  CADDY=$caddy
}

# Copies the app (not .env, bin/, logs/) from where setup.sh is to $DIR, replacing older app files.
copy_app() {
  [ "$SRC" = "$DIR" ] && return
  mkdir -p "$DIR"
  # Packages come with a release zip; from a git checkout, reinstall them when the lock file changed.
  if [ ! -d "$SRC/node_modules" ] && ! cmp -s "$SRC/package-lock.json" "$DIR/package-lock.json"; then rm -rf "$DIR/node_modules"; fi
  rm -rf "$DIR/public" "$DIR/deploy"
  local f
  for f in server.js turn-server.js package.json package-lock.json README.md setup.sh public deploy; do
    [ -e "$SRC/$f" ] && cp -R "$SRC/$f" "$DIR/"
  done
  if [ -d "$SRC/node_modules" ]; then rm -rf "$DIR/node_modules"; cp -R "$SRC/node_modules" "$DIR/"; fi
  if [ -f "$SRC/.env" ] && [ ! -f "$DIR/.env" ]; then
    cp "$SRC/.env" "$DIR/.env"; say "Using the .env next to setup.sh (keeps its tokens)."
  fi
}

write_unit() {
  local name=$1 description=$2 exec=$3 log=$4 extra=${5:-}
  cat > "/etc/systemd/system/$name.service" <<EOF
# Installed by Call Bridge setup ($DIR/deploy/linux/install.sh). Re-run setup instead of editing.
[Unit]
Description=$description
After=network-online.target
Wants=network-online.target

[Service]
User=$SERVICE_USER
Group=$SERVICE_USER
WorkingDirectory=$DIR
ExecStart=$exec
Restart=always
RestartSec=3
StandardOutput=append:$DIR/logs/$log
StandardError=append:$DIR/logs/$log
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
$extra
[Install]
WantedBy=multi-user.target
EOF
}

open_firewall() {
  if command -v ufw >/dev/null && ufw status 2>/dev/null | grep -q '^Status: active'; then
    ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null
    ufw allow 3478/udp >/dev/null; ufw allow 49152:49452/udp >/dev/null
    say 'Opened TCP 80, 443 and UDP 3478, 49152-49452 in ufw.'
  elif command -v firewall-cmd >/dev/null && firewall-cmd --state >/dev/null 2>&1; then
    firewall-cmd -q --permanent --add-port=80/tcp --add-port=443/tcp --add-port=3478/udp --add-port=49152-49452/udp
    firewall-cmd -q --reload
    say 'Opened TCP 80, 443 and UDP 3478, 49152-49452 in firewalld.'
  else
    say 'No active ufw or firewalld; leaving the firewall alone.'
  fi
}

main() {
  while [ $# -gt 0 ]; do
    case $1 in
      --domain) DOMAIN_ARG=${2:?--domain needs a value}; shift 2 ;;
      --ip)     IP=${2:?--ip needs a value}; shift 2 ;;
      --port)   PORT=${2:?--port needs a value}; shift 2 ;;
      --dir)    DIR=${2:?--dir needs a value}; shift 2 ;;
      --yes|-y) YES=1; shift ;;
      -h|--help) sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
      *) die "Unknown option $1 (see --help)." ;;
    esac
  done
  [ "$(id -u)" -eq 0 ] || die 'Run it as root: sudo bash setup.sh'
  [ -d /run/systemd/system ] || die 'This needs a Linux with systemd (Ubuntu, Debian, Rocky, Alma, Fedora, ...).'
  local tool
  for tool in curl tar sha256sum sha512sum awk sed; do
    command -v "$tool" >/dev/null || die "$tool is missing. Install it (e.g. apt install $tool) and run setup again."
  done
  DIR=${DIR%/}
  ENV_FILE="$DIR/.env" CADDYFILE="$DIR/Caddyfile"

  say ''
  say ' Call Bridge server setup'
  say " Installing to $DIR"
  say ''

  # 1. App and software
  copy_app
  id "$SERVICE_USER" >/dev/null 2>&1 ||
    useradd --system --home-dir "$DIR" --no-create-home --shell "$(command -v nologin || echo /bin/false)" "$SERVICE_USER"
  mkdir -p "$DIR/bin" "$DIR/logs" "$DIR/bin/caddy-data" "$DIR/bin/caddy-config"
  get_node
  get_caddy
  if [ ! -d "$DIR/node_modules/ws" ] || [ ! -d "$DIR/node_modules/node-turn" ]; then
    say 'Installing npm packages...'
    (cd "$DIR" && PATH="$(dirname "$NODE"):$PATH" npm ci --omit=dev --no-audit --no-fund)
  fi
  say "Node $("$NODE" --version), Caddy $("$CADDY" version | cut -d' ' -f1)."

  # 2. Settings and tokens
  local old_ip old_domain domain token
  if [ ! -f "$ENV_FILE" ]; then
    {
      say '# Call bridge server settings. Keep this file private: it holds the two tokens.'
      say '# To move the server to another VPS and keep the tokens, copy this file there before running setup.'
      say "BRIDGE_TOKEN=$(new_token)"
      say "OPERATOR_TOKEN=$(new_token)"
      say 'FALLBACK=silence'
    } > "$ENV_FILE"
    say 'Created .env with new tokens.'
  else
    token=$(env_get BRIDGE_TOKEN)
    [ ${#token} -ge 16 ] || die "$ENV_FILE has no BRIDGE_TOKEN (16+ characters). Fix it or delete the file to get new tokens."
    say 'Keeping the tokens in the existing .env.'
  fi
  [ -n "$PORT" ] || PORT=$(env_get PORT)
  [ -n "$PORT" ] || PORT=8080
  [ -n "$IP" ] || IP=$(detect_ip)
  is_public_ipv4 "$IP" || die "Couldn't find this VPS's public IPv4 address. Pass --ip <address>."
  old_ip=$(env_get PUBLIC_IP) old_domain=$(env_get DOMAIN)
  case $DOMAIN_ARG in
    none) domain='' ;;
    '')   domain=$old_domain ;;
    *)    domain=$DOMAIN_ARG ;;
  esac
  domain=$(printf '%s' "$domain" | tr '[:upper:]' '[:lower:]' | sed -E 's#^https?://##; s#/.*$##')
  [ -n "$old_ip" ] && [ "$old_ip" != "$IP" ] && warn "The public IP changed: $old_ip -> $IP."
  env_set HOST 127.0.0.1
  env_set PORT "$PORT"
  env_set PUBLIC_IP "$IP"
  env_set DOMAIN "$domain"
  # Only root and the service may read it.
  chown root:"$SERVICE_USER" "$ENV_FILE"
  chmod 640 "$ENV_FILE"

  # 3. HTTPS
  write_caddyfile "$IP" "$domain" "$PORT"
  "$CADDY" validate --config "$CADDYFILE" --adapter caddyfile >/dev/null 2>&1 ||
    die "Caddy rejected $CADDYFILE. Check --domain. ($CADDY validate --config $CADDYFILE shows why.)"

  # 4. Firewall
  open_firewall
  local busy
  busy=$(ss -Hltnp '( sport = :80 or sport = :443 )' 2>/dev/null | grep -v '"caddy"' | grep -o 'users:(("[^"]*' | cut -d'"' -f2 | sort -u | paste -sd, - || true)
  [ -z "$busy" ] || warn "Warning: port 80 or 443 is already used by $busy (e.g. nginx or apache). Caddy needs both; stop that first."

  # 5. Services
  local live
  live=$(curl -fsS --max-time 3 "http://127.0.0.1:$PORT/healthz" 2>/dev/null | sed -n 's/.*"calls":\([0-9]*\).*/\1/p' || true)
  if [ "${live:-0}" -gt 0 ] && [ "$YES" -eq 0 ]; then
    local answer=''
    read -r -p "$live call(s) are live. Restarting the server now cuts them. Restart anyway? (y/N) " answer || true
    case $answer in [yY]*) ;; *) say 'Stopped without restarting. Settings are saved; run setup again after the calls.'; exit 0 ;; esac
  fi
  # The app is root's and read-only to the service; it writes only logs and Caddy's certificates.
  chown -R root:root "$DIR"
  find "$DIR" \( -path "$DIR/bin/caddy-data" -o -path "$DIR/bin/caddy-config" -o -path "$ENV_FILE" \) -prune \
    -o -exec chmod go+rX,go-w {} +
  chown root:"$SERVICE_USER" "$ENV_FILE"
  chown -R "$SERVICE_USER:$SERVICE_USER" "$DIR/logs" "$DIR/bin/caddy-data" "$DIR/bin/caddy-config"
  chmod +x "$DIR/deploy/linux/"*.sh "$DIR/setup.sh" 2>/dev/null || true

  write_unit callbridge-server 'Call Bridge server' "$NODE --env-file=.env server.js" server.log
  write_unit callbridge-turn 'Call Bridge TURN relay (camera control)' "$NODE --env-file=.env turn-server.js" turn.log
  write_unit callbridge-https 'Call Bridge HTTPS (Caddy)' "$CADDY run --config $CADDYFILE --adapter caddyfile" caddy.log \
"Environment=XDG_DATA_HOME=$DIR/bin/caddy-data XDG_CONFIG_HOME=$DIR/bin/caddy-config
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
"
  ln -sf "$DIR/deploy/linux/callbridge.sh" /usr/local/bin/callbridge
  systemctl daemon-reload
  local s
  for s in callbridge-server callbridge-turn callbridge-https; do
    systemctl enable -q "$s"
    systemctl restart "$s"
    say "Started $s."
  done

  # 6. Check
  local -a addresses
  local -A ok=()
  local a i body mark
  mapfile -t addresses < <(site_names "$IP" "$domain")
  say 'Waiting for the HTTPS certificates (up to 2 minutes)...'
  for ((i = 0; i < 40 && ${#ok[@]} < ${#addresses[@]}; i++)); do
    sleep 3
    for a in "${addresses[@]}"; do
      [ -n "${ok[$a]:-}" ] && continue
      body=$(curl -fsS --max-time 5 "https://$a/healthz" 2>/dev/null || true)
      [[ $body == *'"ok":true'* ]] && ok[$a]=1
    done
  done
  say ''
  if [ ${#ok[@]} -gt 0 ]; then
    printf '\033[32mReady.\033[0m\n'
  else
    warn "Not reachable over HTTPS yet. See $DIR/logs/caddy.log."
    say 'If your VPS provider has its own firewall (e.g. AWS security group, Hetzner Cloud Firewall),'
    say 'allow inbound TCP 80 and 443, and UDP 3478 and 49152-49452, there too.'
  fi
  say ''
  say ' Use any one of these addresses (all reach this server; pick one your networks allow):'
  for a in "${addresses[@]}"; do
    if [ -n "${ok[$a]:-}" ]; then mark='ok     '; else mark='not yet'; fi
    say "   [$mark]  Extension Server URL: wss://$a/call     App: https://$a/"
  done
  say ''
  say " Tokens: sudo callbridge tokens   (they are in $ENV_FILE)"
  say '   Extension side panel -> Access token  = BRIDGE_TOKEN'
  say '   Call Bridge app      -> Operator token = OPERATOR_TOKEN'
  say ''
  say ' Manage it with: callbridge status | logs | restart | stop | start | uninstall'
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then main "$@"; fi
